package com.lai.recipesender.model;

/**
 * 一台绑定目标此刻在不在跑配方。
 *
 * <p>1.0.34 起「发送到已绑定容器」与「直达」都只往空闲机器投料、只给空闲机器调电路：机器跑到一半
 * 被改电路，手上那一炉就会按新电路重新匹配，玩家看到的是「明明在跑却换了配方」。
 *
 * <p>{@link #NOT_A_MACHINE} 同时承担「探不出来」这一种情况：普通箱子、储罐、AE2 存储本来就没有配方
 * 逻辑，而拿不到机器实例（模组缺失、部件挂不上控制器）时也只能当成没有配方逻辑。两种情况下都按
 * 「不会被打断」处理，也就是照旧投料——探不出来绝不能变成少送一份。
 *
 * <p>放在 model 包是因为这个枚举要上网络（服务端算、客户端显示）；client 包引用了 GUI，
 * 专用服务端加载会崩。
 */
public enum MachineState {

    /** 不是配方机器（箱子、储罐、AE2 存储），或者探不到配方逻辑。 */
    NOT_A_MACHINE,

    /** 空闲：可以投料，也可以改电路。 */
    IDLE,

    /** 正在跑（含等料、输出满）：不投料、不改电路。 */
    BUSY
}
